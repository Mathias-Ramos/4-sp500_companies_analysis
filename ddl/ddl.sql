CREATE TABLE IF NOT EXISTS COMPANIES (
    TICKER VARCHAR(500) NOT NULL,
    NAME VARCHAR(500),
    SECTOR VARCHAR(500),
    INDUSTRY VARCHAR(500),
    COUNTRY VARCHAR(500),
    CURRENCY VARCHAR(500),
    MARKET_CAP NUMBER(38,0),
    TTM_EBITDA NUMBER(38,0),

    CONSTRAINT PK_COMPANIES PRIMARY KEY (TICKER)
);


CREATE TABLE IF NOT EXISTS PRICES_WEEKLY (
    TICKER VARCHAR(500) NOT NULL,
    DATE DATE NOT NULL,
    ADJ_CLOSE FLOAT,
    MARKET_CAP FLOAT,
    ENTERPRISE_VALUE FLOAT,
    TRAILING_PE FLOAT,
    FORWARD_PE FLOAT,
    PEG_RATIO FLOAT,
    PRICE_SALES FLOAT,
    PRICE_BOOK FLOAT,
    EV_REVENUE FLOAT,
    EV_EBITDA FLOAT,

    CONSTRAINT PK_PRICES_WEEKLY PRIMARY KEY (TICKER, DATE),
    CONSTRAINT FK_PRICES_WEEKLY_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);


CREATE TABLE IF NOT EXISTS INCOME_STMT (
    TICKER VARCHAR(500) NOT NULL,
    DATE DATE NOT NULL,
    REVENUE FLOAT,
    EBIT FLOAT,
    EBITDA FLOAT,
    TAX_PROVISION FLOAT,
    PRETAX_INCOME FLOAT,
    NET_INCOME FLOAT,
    DILUTED_EPS FLOAT,

    CONSTRAINT PK_INCOME_STMT PRIMARY KEY (TICKER, DATE),
    CONSTRAINT FK_INCOME_STMT_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);


CREATE TABLE IF NOT EXISTS BALANCE_SHEET (
    TICKER VARCHAR(500) NOT NULL,
    DATE DATE NOT NULL,
    TOTAL_DEBT FLOAT,
    CASH_AND_EQUIVALENTS FLOAT,
    STOCKHOLDERS_EQUITY FLOAT,
    INVESTED_CAPITAL FLOAT,
    NET_DEBT FLOAT,
    TOTAL_ASSETS FLOAT,
    CASH_AND_SHORT_TERM_INVESTMENTS FLOAT,

    CONSTRAINT PK_BALANCE_SHEET PRIMARY KEY (TICKER, DATE),
    CONSTRAINT FK_BALANCE_SHEET_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);


CREATE TABLE IF NOT EXISTS CASHFLOW (
    TICKER VARCHAR(500) NOT NULL,
    DATE DATE NOT NULL,
    OPERATING_CASH_FLOW FLOAT,
    CAPITAL_EXPENDITURE FLOAT,

    CONSTRAINT PK_CASHFLOW PRIMARY KEY (TICKER, DATE),
    CONSTRAINT FK_CASHFLOW_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);


CREATE TABLE IF NOT EXISTS ANALYST_ESTIMATES (
    TICKER VARCHAR(500) NOT NULL,
    PERIOD VARCHAR(500) NOT NULL,
    EPS_AVG FLOAT,
    EPS_LOW FLOAT,
    EPS_HIGH FLOAT,
    EPS_YEAR_AGO FLOAT,
    EPS_NUMBER_OF_ANALYSTS NUMBER(38,0),
    EPS_GROWTH FLOAT,
    REVENUE_AVG NUMBER(38,0),
    REVENUE_LOW NUMBER(38,0),
    REVENUE_HIGH NUMBER(38,0),
    REVENUE_YEAR_AGO FLOAT,
    REVENUE_NUMBER_OF_ANALYSTS NUMBER(38,0),
    REVENUE_GROWTH FLOAT,
    TREND_CURRENT FLOAT,
    TREND_7_DAYS_AGO FLOAT,
    TREND_30_DAYS_AGO FLOAT,
    TREND_60_DAYS_AGO FLOAT,
    TREND_90_DAYS_AGO FLOAT,
    UP_LAST_7_DAYS NUMBER(38,0),
    UP_LAST_30_DAYS NUMBER(38,0),
    DOWN_LAST_30_DAYS NUMBER(38,0),
    DOWN_LAST_7_DAYS NUMBER(38,0),
    CURRENCY VARCHAR(500),
    METHODOLOGY VARCHAR(500),

    CONSTRAINT PK_ANALYST_ESTIMATES PRIMARY KEY (TICKER, PERIOD),
    CONSTRAINT FK_ANALYST_ESTIMATES_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);

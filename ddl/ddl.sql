CREATE OR REPLACE TABLE COMPANIES (
    TICKER VARCHAR(500) NOT NULL,
    NAME VARCHAR(500),
    SECTOR VARCHAR(500),
    INDUSTRY VARCHAR(500),
    COUNTRY VARCHAR(500),
    CURRENCY VARCHAR(500),

    CONSTRAINT PK_COMPANIES PRIMARY KEY (TICKER)
);


CREATE OR REPLACE TABLE PRICES_DAILY (
    TICKER VARCHAR(500) NOT NULL,
    DATE DATE NOT NULL,
    ROUNDED_CLOSE FLOAT,

    CONSTRAINT PK_PRICES_DAILY PRIMARY KEY (TICKER, DATE),
    CONSTRAINT FK_PRICES_DAILY_COMPANIES FOREIGN KEY (TICKER) REFERENCES COMPANIES(TICKER)
);


